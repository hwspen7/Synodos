"""Reproducible, reference-backed comparison of optional speaker models.

Two independent tasks:
- diarization: compare existing CAM++ live replay with Nemotron 3 on one WAV;
- verification: compare CAM++ and ECAPA embeddings on the same labeled pairs.

No reference data is generated by the models. Results contain aggregate
metrics, opaque case IDs, and model names only; no voiceprints or speech text.
Run the optional models *after* meeting recording, in a dedicated environment.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import time

import numpy as np

from speech.speaker_backends import (
    create_diarization_backend, create_embedding_backend, validated_audio,
)
from tools.phase07_benchmark import load_wav
from tools.phase09_speaker_benchmark import evaluate

SCHEMA = "meeting-speaker-stage1-comparison-v1"
MANIFEST_SCHEMA = "meeting-speaker-stage1-manifest-v1"


def _fingerprint(path: Path) -> str:
    digest = sha256()
    with path.open("rb") as src:
        for chunk in iter(lambda: src.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verified_path(root: Path, item: dict) -> Path:
    """Require a local, immutable, relative WAV under the selected corpus."""
    if not isinstance(item, dict):
        raise ValueError("Invalid audio source descriptor")
    value, checksum = item.get("audio"), item.get("sha256")
    if not isinstance(value, str) or not value or not isinstance(checksum, str):
        raise ValueError("Audio path and sha256 are required")
    target = (root / value).resolve()
    if (not target.is_relative_to(root.resolve())
            or target.suffix.lower() != ".wav" or not target.is_file()):
        raise ValueError("Audio must be a local WAV inside corpus root")
    if _fingerprint(target) != checksum.lower():
        raise ValueError("Audio checksum mismatch")
    return target


def load_manifest(path: Path) -> dict:
    if not path.is_file():
        raise FileNotFoundError("Frozen stage-one manifest was not found")
    doc = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict) or doc.get("schema") != MANIFEST_SCHEMA:
        raise ValueError("Invalid stage-one manifest schema")
    for field in ("diarization_cases", "verification_pairs"):
        items = doc.get(field, [])
        if not isinstance(items, list) or len(items) > 500:
            raise ValueError(f"Invalid number of {field}")
        ids = [row.get("id") for row in items if isinstance(row, dict)]
        if (len(ids) != len(items) or any(not isinstance(x, str) or not x for x in ids)
                or len(ids) != len(set(ids))):
            raise ValueError(f"Missing or duplicate case ID in {field}")
    return doc


def baseline_turns(record: dict, *, duration_ms: int) -> list[dict]:
    """Read the final anonymous timeline from the live CAM++ replay."""
    if (record.get("delivery_matched") is not True
            or record.get("server_closed") is not True
            or record.get("errors") or record.get("flags")):
        raise ValueError("Baseline live replay was not completed cleanly")
    if abs(float(record.get("source_audio_duration_s", -1)) * 1000 - duration_ms) > 30:
        raise ValueError("Baseline audio duration does not match case")
    timeline = (record.get("final_cluster_diagnostics") or {}).get("anonymous_timeline")
    if (not isinstance(timeline, dict) or timeline.get("truncated") is not False):
        raise ValueError("Baseline speaker timeline missing or truncated")
    segments = timeline.get("segments")
    if not isinstance(segments, list) or len(segments) != timeline.get("total_segments"):
        raise ValueError("Incomplete baseline segment timeline")
    result = []
    for item in segments:
        if not isinstance(item, dict):
            raise ValueError("Invalid baseline timeline")
        sid = item.get("published_speaker_id")
        if type(sid) is not int or sid <= 0:
            continue
        a, b = item.get("start_ms"), item.get("end_ms")
        if (type(a) is not int or type(b) is not int
                or a < 0 or b <= a or b > duration_ms + 30):
            raise ValueError("Invalid baseline segment time")
        result.append({
            "start_ms": a, "end_ms": min(b, duration_ms),
            "speaker_id": sid,
        })
    return result


def _reference_turns(items: object, duration_ms: int) -> list[dict]:
    if not isinstance(items, list) or not items or len(items) > 10000:
        raise ValueError("Human reference speaker turns are required")
    checked = []
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Invalid human reference")
        a, b, speaker = (
            item.get("start_ms"), item.get("end_ms"), item.get("speaker"),
        )
        if (type(a) is not int or type(b) is not int or a < 0
                or b <= a or b > duration_ms or not isinstance(speaker, str)
                or not speaker.strip()):
            raise ValueError("Invalid human-annotated turn")
        checked.append({"start_ms": a, "end_ms": b, "speaker": speaker})
    return checked


def diarization_details(reference: list[dict], predicted: list[dict],
                        der_result: dict) -> dict:
    """Count speakers and score complete recovery during annotated overlap."""
    mapping = der_result["speaker_mapping"]
    ref_names = {turn["speaker"] for turn in reference}
    hyp_names = {turn["speaker_id"] for turn in predicted}
    step_ms = der_result["frame_step_ms"]
    duration = max(
        [turn["end_ms"] for turn in reference + predicted], default=0
    )
    overlap_frames = 0
    overlap_correct = 0
    for time_ms in range(0, duration, step_ms):
        real = {
            str(t["speaker"]) for t in reference
            if t["start_ms"] <= time_ms < t["end_ms"]
        }
        if len(real) < 2:
            continue
        observed = {
            mapping.get(str(t["speaker_id"]))
            for t in predicted
            if t["start_ms"] <= time_ms < t["end_ms"]
        }
        overlap_frames += 1
        overlap_correct += real.issubset(observed)
    return {
        "reference_speaker_count": len(ref_names),
        "predicted_speaker_count": len(hyp_names),
        "speaker_count_absolute_error": abs(len(hyp_names) - len(ref_names)),
        "overlap_reference_frames": overlap_frames,
        "overlap_all_speakers_recall": (
            round(overlap_correct / overlap_frames, 5)
            if overlap_frames else None
        ),
        "overlap_note": (
            "All reference speakers must be active in a mapped predicted "
            "channel during each annotated overlap frame."
        ),
    }


def _score_diarization(reference: list[dict], predicted: list[dict]) -> dict:
    result = evaluate(reference, predicted)
    details = diarization_details(reference, predicted, result)
    # Human reference speaker names are private. The matching map is only
    # needed transiently for scoring and must not be exported to reports.
    result.pop("speaker_mapping", None)
    return {**result, **details}


def _summarize_diarization(rows: list[dict]) -> dict:
    done = [x for x in rows if x.get("metrics")]
    total_seconds = sum(x["metrics"]["reference_speaker_seconds"] for x in done)
    # DER is weighted by each case's reference speaker-time, not sample count.
    der = (sum(x["metrics"]["der"] * x["metrics"]["reference_speaker_seconds"]
               for x in done) / total_seconds) if total_seconds else None
    timed = [x["inference_ms"] for x in done if x.get("inference_ms") is not None]
    return {
        "requested": len(rows), "completed": len(done),
        "failed": len(rows) - len(done),
        "reference_weighted_der": round(der, 5) if der is not None else None,
        "reference_speaker_seconds": round(total_seconds, 2),
        "mean_inference_ms": (
            round(sum(timed) / len(timed), 1) if timed else None
        ),
    }


def compare_diarization(cases: list[dict], root: Path, *,
                        nemotron=None, device: str = "cpu") -> dict:
    if not cases:
        raise ValueError("No diarization cases in manifest")
    outputs = {"camplus_live": [], "nemotron3": []}
    model = nemotron if nemotron is not None else create_diarization_backend(
        "nemotron3", device=device,
    )
    for case in cases:
        # Input and label errors invalidate the whole benchmark, not just one
        # model, because both must be compared on identical immutable audio.
        path = verified_path(root, case)
        samples = validated_audio(load_wav(path))
        duration_ms = round(len(samples) * 1000 / 16000)
        reference = _reference_turns(case.get("reference_turns"), duration_ms)
        baseline = case.get("camplus_replay")
        if not isinstance(baseline, dict):
            raise ValueError("Each paired case needs a frozen CAM++ replay descriptor")
        baseline_path = (root / str(baseline.get("path", ""))).resolve()
        if (not baseline_path.is_relative_to(root.resolve())
                or not baseline_path.is_file()
                or _fingerprint(baseline_path) != baseline.get("sha256")):
            raise ValueError("Baseline replay missing or checksum changed")
        old = json.loads(baseline_path.read_text(encoding="utf-8"))
        # Compare source filename as well as duration; do not compare the
        # correct duration from a different meeting by accident.
        source_name = str(old.get("source_audio") or "").replace("\\", "/").split("/")[-1]
        if source_name != path.name:
            raise ValueError("Baseline replay source WAV does not match case")
        if old.get("source_audio_sha256") != case["sha256"]:
            raise ValueError(
                "Baseline replay source WAV checksum missing or mismatched. "
                "Regenerate the replay with current tools/live_caption_ws_replay.py"
            )
        baseline_predictions = baseline_turns(old, duration_ms=duration_ms)
        outputs["camplus_live"].append({
            "id": case["id"],
            "inference_ms": None,  # replay already ran; no invented latency
            "metrics": _score_diarization(reference, baseline_predictions),
        })
        try:
            started = time.perf_counter()
            predicted = model.diarize(samples)
            elapsed = round((time.perf_counter() - started) * 1000, 1)
            outputs["nemotron3"].append({
                "id": case["id"], "inference_ms": elapsed,
                "metrics": _score_diarization(reference, predicted),
            })
        except Exception as exc:
            # Model inference failures are explicit, never zero DER.
            outputs["nemotron3"].append({
                "id": case["id"],
                "error": f"{type(exc).__name__}: {str(exc)[:160]}",
            })
    result = {
        "models": {name: {
            "summary": _summarize_diarization(items),
            "cases": items,
        } for name, items in outputs.items()},
        "comparison_limit": (
            "CAM++ live ASR-aligned segments and Nemotron offline acoustic "
            "turns use different boundary pipelines. Only compare on the "
            "same human reference with explicit coverage and overlap analysis."
        ),
    }
    result["paired_completed"] = sum(
        bool(a.get("metrics")) and bool(b.get("metrics"))
        for a, b in zip(outputs["camplus_live"], outputs["nemotron3"])
    )
    return result


def cosine(a: np.ndarray | None, b: np.ndarray | None) -> float | None:
    if a is None or b is None or a.shape != b.shape:
        return None
    return float(np.dot(a, b))


def verification_metrics(rows: list[tuple[bool, float]],
                         threshold: float | None) -> dict:
    """Report EER as descriptive; operational threshold must be predeclared."""
    positives = sorted([score for same, score in rows if same])
    negatives = sorted([score for same, score in rows if not same])
    if not positives or not negatives:
        return {
            "eer": None, "auc": None, "far": None, "frr": None,
            "threshold": threshold, "reason": "Need both positive and negative trials",
        }
    auc = sum(
        (1.0 if pos > neg else 0.5 if pos == neg else 0.0)
        for pos in positives for neg in negatives
    ) / (len(positives) * len(negatives))
    candidates = sorted(
        set([-1.0001, 1.0001, *positives, *negatives])
    )
    all_rates = [
        (
            sum(score >= t for score in negatives) / len(negatives),
            sum(score < t for score in positives) / len(positives),
        ) for t in candidates
    ]
    far_eer, frr_eer = min(all_rates, key=lambda pair: (
        abs(pair[0] - pair[1]), (pair[0] + pair[1]) / 2,
    ))
    far = frr = None
    if threshold is not None:
        if not -1 <= threshold <= 1:
            raise ValueError("Verification threshold must be in [-1, 1]")
        far = sum(score >= threshold for score in negatives) / len(negatives)
        frr = sum(score < threshold for score in positives) / len(positives)
    return {
        "eer": round((far_eer + frr_eer) / 2, 5),
        "auc": round(auc, 5),
        "far": round(far, 5) if far is not None else None,
        "frr": round(frr, 5) if frr is not None else None,
        "threshold": threshold,
        "note": "EER post-hoc descriptive, never a tuned production threshold",
    }


def compare_verification(pairs: list[dict], root: Path, *,
                         backends: dict | None = None,
                         thresholds: dict | None = None,
                         ecapa_device: str = "cpu",
                         selected: str = "both") -> dict:
    if not pairs:
        raise ValueError("No verification pairs in manifest")
    if selected not in ("camplus", "ecapa", "both"):
        raise ValueError("Invalid selected verification backend")
    own_manager = None
    if backends is None:
        backends = {}
        if selected in ("camplus", "both"):
            from core.config import Settings
            from inference.models import ModelManager
            own_manager = ModelManager(Settings())
            backends["camplus"] = create_embedding_backend(
                "camplus", manager=own_manager,
            )
        if selected in ("ecapa", "both"):
            backends["ecapa"] = create_embedding_backend(
                "ecapa", device=ecapa_device,
            )
    thresholds = thresholds or {}
    results = {}
    try:
        for name, backend in backends.items():
            cache = {}
            successful = []
            failures = []
            started = time.perf_counter()
            for pair in pairs:
                left = verified_path(root, pair.get("left"))
                right = verified_path(root, pair.get("right"))
                if type(pair.get("same_speaker")) is not bool:
                    raise ValueError("Human same_speaker label must be boolean")
                try:
                    def embedding(path):
                        key = _fingerprint(path)
                        if key not in cache:
                            cache[key] = backend.embed(validated_audio(load_wav(path)))
                        return cache[key]
                    score = cosine(embedding(left), embedding(right))
                    if score is None:
                        raise ValueError("Missing or incompatible embedding")
                    successful.append((pair["same_speaker"], score))
                except Exception as exc:
                    failures.append({
                        "id": pair["id"],
                        "error": f"{type(exc).__name__}: {str(exc)[:160]}",
                    })
            results[name] = {
                "requested": len(pairs), "completed": len(successful),
                "failed": len(failures), "failures": failures,
                "elapsed_ms": round((time.perf_counter() - started) * 1000, 1),
                "metrics": verification_metrics(successful, thresholds.get(name)),
                "embedding_model": backend.model_id,
            }
    finally:
        if own_manager is not None:
            own_manager.close()
    return {
        "models": results,
        "paired_trials_required": True,
        "selected_backend": selected,
        "pair_count": len(pairs),
        "note": (
            "Only same-model cosine scores are valid. Never mix CAM++ and "
            "ECAPA vectors, and never report EER as a calibrated threshold."
        ),
    }


def run(path: Path, root: Path, mode: str, *, nemotron=None,
        backends=None, thresholds=None, diar_device="cpu",
        ecapa_device="cpu", verification_backend="both") -> dict:
    doc = load_manifest(path)
    result = {
        "schema": SCHEMA,
        "manifest_sha256": _fingerprint(path),
        "diarization": None,
        "verification": None,
        "reference_status": "operator_supplied_not_independently_verified",
        "verification_provenance": doc.get("verification_provenance"),
        "candidate_models_not_promoted": True,
    }
    if mode in ("diarization", "both"):
        result["diarization"] = compare_diarization(
            doc.get("diarization_cases", []), root, nemotron=nemotron,
            device=diar_device,
        )
    if mode in ("verification", "both"):
        result["verification"] = compare_verification(
            doc.get("verification_pairs", []), root, backends=backends,
            thresholds=thresholds, ecapa_device=ecapa_device,
            selected=verification_backend,
        )
    return result


def complete(report: dict) -> bool:
    if report["diarization"] is not None:
        diar = report["diarization"]
        if diar["paired_completed"] != diar["models"]["camplus_live"]["summary"]["requested"]:
            return False
    if report["verification"] is not None:
        verif = report["verification"]["models"]
        if not verif or any(x["completed"] != x["requested"]
                            or x["metrics"]["eer"] is None for x in verif.values()):
            return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("benchmark/fixed195"))
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--mode", choices=["diarization", "verification", "both"],
                        required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--diar-device", choices=("cpu", "cuda"), default="cpu")
    parser.add_argument("--ecapa-device", choices=("cpu", "cuda"), default="cpu")
    parser.add_argument("--verification-backend",
                        choices=("camplus", "ecapa", "both"), default="both",
                        help="Select one model to run in its isolated environment")
    parser.add_argument("--camplus-threshold", type=float)
    parser.add_argument("--ecapa-threshold", type=float)
    args = parser.parse_args()
    for t in (args.camplus_threshold, args.ecapa_threshold):
        if t is not None and not -1 <= t <= 1:
            parser.error("Thresholds must lie within [-1, 1]")
    if args.output.exists():
        parser.error("Refusing to overwrite prior comparison report")
    if args.output.resolve() == args.manifest.resolve():
        parser.error("Output must differ from the source manifest")
    report = run(
        args.manifest, args.root, args.mode,
        thresholds={
            "camplus": args.camplus_threshold,
            "ecapa": args.ecapa_threshold,
        },
        diar_device=args.diar_device,
        ecapa_device=args.ecapa_device,
        verification_backend=args.verification_backend,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as stream:
        json.dump(report, stream, indent=2)
        stream.write("\n")
    print(json.dumps(report, indent=2))
    return 0 if complete(report) else 1


if __name__ == "__main__":
    raise SystemExit(main())
